-- 增量迁移，仅执行一次。执行前备份；不要导入用户的结构导出（含 DROP TABLE）。
CREATE TABLE IF NOT EXISTS user_extra (
 owner VARCHAR(90) PRIMARY KEY, gender VARCHAR(12) NOT NULL DEFAULT '保密', birth_date DATE NULL,
 school VARCHAR(120) NOT NULL DEFAULT '', education VARCHAR(40) NOT NULL DEFAULT '',
 recipient VARCHAR(60) NOT NULL DEFAULT '', phone VARCHAR(30) NOT NULL DEFAULT '', address VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS product_detail (
 ad_id BIGINT PRIMARY KEY, origin VARCHAR(120) NOT NULL DEFAULT '', blocks MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
ALTER TABLE order_record ADD COLUMN received_time DATETIME NULL, ADD COLUMN shipping_snapshot VARCHAR(700) NULL;
CREATE TABLE IF NOT EXISTS community_user (
 owner VARCHAR(90) PRIMARY KEY, warnings INT NOT NULL DEFAULT 0, muted_until DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_post (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner VARCHAR(90) NOT NULL, author VARCHAR(100) NOT NULL,
 title VARCHAR(120) NOT NULL, blocks MEDIUMTEXT NOT NULL, search_text MEDIUMTEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PUBLIC', featured BOOLEAN NOT NULL DEFAULT FALSE,
 pinned BOOLEAN NOT NULL DEFAULT FALSE, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_feed(status,pinned,created_at), INDEX idx_owner(owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_reply (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, post_id BIGINT NOT NULL, owner VARCHAR(90) NOT NULL,
 author VARCHAR(100) NOT NULL, content TEXT NOT NULL, parent_id BIGINT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_post(post_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_view (
 post_id BIGINT NOT NULL, owner VARCHAR(90) NOT NULL, view_day DATE NOT NULL,
 PRIMARY KEY(post_id,owner,view_day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_like (
 post_id BIGINT NOT NULL, owner VARCHAR(90) NOT NULL, PRIMARY KEY(post_id,owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_notice (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner VARCHAR(90) NOT NULL, post_id BIGINT NULL,
 kind VARCHAR(30) NOT NULL, message VARCHAR(500) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_notice(owner,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_word (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, word VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
