import request from './request'
export const merchantProfile = () => request.get('/api/merchant/profile')
export const saveMerchantProfile = data => request.put('/api/merchant/profile', data)
export const merchantStats = () => request.get('/api/merchant/stats')
export const merchantList = (kind, params) => request.get(`/api/merchant/${kind}`, { params })
export const saveMerchantItem = (kind, data) => data.id ? request.put(`/api/merchant/${kind}/${data.id}`, data) : request.post(`/api/merchant/${kind}`, data)
export const withdrawMerchantItem = (kind, id) => request.post(`/api/merchant/${kind}/${id}/withdraw`)
export const productOptions = keyword => request.get('/api/merchant/product-options', { params: { keyword } })
export const shipMerchantOrder = (id, data) => request.put(`/api/merchant/orders/${id}/logistics`, data)
export const replyMerchantAfterSale = (id, data) => request.put(`/api/merchant/orders/${id}/after-sale`, data)
export const listMerchants = params => request.get('/api/admin/merchants', { params })
export const inviteMerchant = () => request.post('/api/admin/merchants/invitations')
export const reviewCounts = () => request.get('/api/admin/commerce/counts')
export const reviewList = (kind, params) => request.get(`/api/admin/commerce/${kind}`, { params })
export const reviewItem = (kind, id, data) => request.post(`/api/admin/commerce/${kind}/${id}/review`, data)
export const locationAvailable = () => request.get('/api/merchant/location/available')
export const locateCity = (lat, lon) => request.get('/api/merchant/location/city', { params: { lat, lon } })
export const publicCampaigns = () => request.get('/api/shop/campaigns', { silent: true })

export const saveMerchantAvatar = avatar => request.put('/api/merchant/avatar', { avatar })
export const setMerchantBanned = (id, banned, reason, duration = 'PERMANENT') => request.put(`/api/admin/merchants/${id}/ban`, { banned, reason, duration })
export const deleteMerchantOrder = id => request.delete(`/api/merchant/orders/${id}`)
export const fetchMerchantStore = id => request.get(`/api/shop/merchants/${id}`, { silent: true })

export const saveMerchantCover = coverUrl => request.put('/api/merchant/cover', { coverUrl })

export const carouselSettings = () => request.get('/api/admin/commerce/carousel')
export const saveCarouselSettings = data => request.put('/api/admin/commerce/carousel', data)
export const selectCarouselCampaign = (id, data) => request.put(`/api/admin/commerce/campaigns/${id}/carousel`, data)
export const publicCarousel = () => request.get('/api/shop/carousel', { silent: true })
